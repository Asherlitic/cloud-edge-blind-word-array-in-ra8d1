void uart3_write_byte (const uint8 dat)
{
    uart_send_complete_flag = false;
    g_uart3.p_api->write(g_uart3.p_ctrl, (const uint8*)&dat, 1);     // ���͵�����
    while(!uart_send_complete_flag);
}

